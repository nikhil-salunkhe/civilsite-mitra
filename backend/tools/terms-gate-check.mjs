const BASE='http://localhost:5000/api';
let pass=0, fail=0;
const ok=(n,c)=>{ if(c){pass++;console.log('PASS ',n);} else {fail++;console.log('FAIL ',n);} };
const j=async(m,p,t,b)=>{const r=await fetch(BASE+p,{method:m,headers:{'Content-Type':'application/json',...(t?{Authorization:'Bearer '+t}:{})},body:b?JSON.stringify(b):undefined});return{status:r.status,body:await r.json().catch(()=>({}))};};
(async()=>{
  const creds={email:process.env.SUPER_ADMIN_EMAIL||'admin@civilsitemitra.com',password:process.env.SUPER_ADMIN_PASSWORD||'Admin@123456'};
  const admin=await j('POST','/auth/login',null,creds);
  const at=admin.body.token;
  ok('admin logs in',!!at);
  ok('admin exempt from terms gate',admin.body.data.mustAcceptTerms===false);
  const rid=Date.now();
  const eng={name:'TC Gate Test',email:`tcgate.${rid}@test.com`,mobile:`93${String(rid).slice(-8)}`,company:'TC Constructions',password:'GateTest@123',customPassword:'GateTest@123',status:'ACTIVE'};
  const created=await j('POST','/admin/engineers',at,eng);
  const e=created.body.data?.engineer||created.body.data?.user;
  ok('engineer created',created.status<300&&!!e?._id);
  if(!e?._id){console.log('create response:',JSON.stringify(created.body).slice(0,300));process.exit(1);}
  const login=await j('POST','/auth/login',null,{email:eng.email,password:'GateTest@123'});
  ok('engineer logs in with issued credentials',login.status===200);
  ok('login reports mustAcceptTerms=true',login.body.data?.mustAcceptTerms===true);
  ok('login reports mustChangePassword=true',login.body.data?.mustChangePassword===true);
  const et=login.body.token;
  const me=await j('GET','/auth/me',et);
  ok('GET /me also reports the gate',me.body.data?.mustAcceptTerms===true);
  const bad=await j('POST','/auth/accept-terms',et,{accepted:false});
  ok('accept-terms rejects accepted:false',bad.status===400);
  const acc=await j('POST','/auth/accept-terms',et,{accepted:true});
  ok('accept-terms succeeds',acc.status===200);
  ok('acceptance records the version',acc.body.data?.termsVersion==='2026-10');
  ok('acceptance is timestamped',!!acc.body.data?.termsAcceptedAt);
  const me2=await j('GET','/auth/me',et);
  ok('gate cleared after acceptance',me2.body.data?.mustAcceptTerms===false);
  ok('password gate still pending (flow order)',me2.body.data?.mustChangePassword===true);
  const anon=await j('POST','/auth/accept-terms',null,{accepted:true});
  ok('anonymous cannot accept terms',anon.status===401);
  const del=await fetch(BASE+'/admin/engineers/'+e._id,{method:'DELETE',headers:{Authorization:'Bearer '+at}});
  ok('cleanup: engineer deleted',del.status===200);
  console.log(`\n=== TERMS_GATE_CHECK pass=${pass} fail=${fail} ===`);
  process.exit(fail?1:0);
})().catch(e=>{console.error('ERROR',e.message);process.exit(1);});
